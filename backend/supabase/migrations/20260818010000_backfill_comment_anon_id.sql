-- =============================================================================
-- 기존 댓글의 익명 표기 정리 (2026-08-18)
-- =============================================================================
-- 앞선 마이그레이션(20260818000000)은 '앞으로 달릴 댓글'만 고친다.
-- 이미 저장된 댓글에 남아 있는 문제를 여기서 정리한다.
--
-- 진단 결과 (실측):
--   · 서로 다른 사람이 같은 번호를 쓰는 진짜 중복: 0건
--     ("익명 3"이 9번 나오는 건 한 사람이 9번 단 것으로, 새 규칙상 정상)
--   · 닉네임이 그대로 저장된 댓글: '아이고', '변종현', '나 재욱', '나나나'
--   · 사연이 삭제됐는데 남아 있는 고아 댓글
--   · 번호에 빈 칸 (story-etc-1 은 1과 5만 존재)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 고아 댓글 삭제
-- -----------------------------------------------------------------------------
-- 사연이 지워졌으므로 화면에 뜨지 않고 조회할 경로도 없다.
-- 닉네임이 남아 있는 댓글 대부분이 여기 속한다.
delete from public.comments c
where not exists (select 1 from public.stories s where s."id" = c."storyId");

-- -----------------------------------------------------------------------------
-- 2. 사연 작성자의 댓글은 '글쓴이'로
-- -----------------------------------------------------------------------------
update public.comments c
   set "anonymousId" = '글쓴이'
  from public.stories s
 where s."id" = c."storyId"
   and s."authorId" = c."authorId"
   and c."anonymousId" <> '글쓴이';

-- -----------------------------------------------------------------------------
-- 3. 나머지는 사람별로 번호를 다시 매긴다
-- -----------------------------------------------------------------------------
-- 한 사연 안에서 (처음 댓글을 단 순서)대로 1, 2, 3... 을 부여한다.
-- 같은 사람의 댓글은 전부 같은 번호를 갖게 되고, 빈 칸도 사라진다.
with ranked as (
  select c."storyId",
         c."authorId",
         row_number() over (
           partition by c."storyId"
           order by min(c."createdAt"), c."authorId"
         ) as n
    from public.comments c
    join public.stories s on s."id" = c."storyId"
   where c."authorId" <> s."authorId"
   group by c."storyId", c."authorId"
)
update public.comments c
   set "anonymousId" = '익명 ' || r.n
  from ranked r
 where c."storyId" = r."storyId"
   and c."authorId" = r."authorId"
   and c."anonymousId" <> '익명 ' || r.n;
